"""Build the blog index and standalone HTML posts from Markdown and TeX."""

from dataclasses import dataclass
from datetime import date
from html import escape
from pathlib import Path
import re
from string import Template
import subprocess
import tomllib


ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / '_blog'
OUTPUT = ROOT / 'blog'
GENERATED = '<!-- Generated by scripts/build_blog.py. -->'


@dataclass
class Post:
    slug: str
    title: str
    published: date
    summary: str
    language: str
    body: str


def read_post(path):
    if not re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*', path.stem):
        raise ValueError('Use a filename such as my-first-post.md.')
    text = path.read_text(encoding='utf-8')
    if not text.startswith('+++\n'):
        raise ValueError('Start the post with a TOML header between +++ lines.')
    header, separator, markdown = text[4:].partition('\n+++\n')
    if not separator:
        raise ValueError('Close the TOML header with +++ and start the post on a new line.')
    metadata = tomllib.loads(header)
    title = metadata.get('title')
    if not isinstance(title, str) or not title.strip():
        raise ValueError('Provide a title in the TOML header.')
    published = date.fromisoformat(str(metadata.get('date', '')))
    summary = metadata.get('summary', '')
    language = metadata.get('lang', 'en')
    if not isinstance(summary, str) or not isinstance(language, str):
        raise ValueError('Use strings for summary and lang.')

    body = subprocess.run(
        [
            'pandoc', '--from=markdown+tex_math_single_backslash-raw_html-raw_tex',
            '--to=html5', '--mathml', '--shift-heading-level-by=1', '--no-highlight',
            '--fail-if-warnings', '--lua-filter', str(SOURCE / 'links.lua'),
        ],
        input=markdown, text=True, encoding='utf-8', capture_output=True, check=True,
    ).stdout
    return Post(path.stem, title.strip(), published, summary, language, body)


def date_label(published):
    return f'<time class="blog-date" datetime="{published}">{published}</time>'


def render_index(posts):
    if not posts:
        return '        <p class="blog-empty">No posts yet.</p>'
    entries = []
    for post in posts:
        summary = f'\n            <p>{escape(post.summary)}</p>' if post.summary else ''
        entries.append(
            '          <li>\n'
            f'            <h2><a href="blog/{post.slug}.html">{escape(post.title)}</a></h2>\n'
            f'            {date_label(post.published)}{summary}\n'
            '          </li>'
        )
    return '\n'.join(['        <ul class="blog-list">', *entries, '        </ul>'])


def render_post(post, template):
    title = escape(post.title)
    header = (
        '          <p class="blog-back"><a href="../blog.html">← Blog</a></p>\n'
        f'          <h1>{title}</h1>\n'
        f'          {date_label(post.published)}'
    )
    content = f'        <article class="blog-prose">\n{post.body}        </article>'
    return template.substitute(
        root='../', page=f'blog/{post.slug}.html', kind='article',
        title=title, description=escape(post.summary or post.title),
        language=escape(post.language), header=header, content=content,
    )


def main():
    template = Template((SOURCE / 'page.html').read_text(encoding='utf-8'))
    posts = []
    for path in sorted(SOURCE.glob('*.md')):
        try:
            posts.append(read_post(path))
        except (OSError, ValueError, subprocess.CalledProcessError) as error:
            detail = error.stderr.strip() if isinstance(error, subprocess.CalledProcessError) else str(error)
            raise SystemExit(f'{path.relative_to(ROOT)}: {detail}') from error
    posts.sort(key=lambda post: post.published, reverse=True)

    pages = {
        ROOT / 'blog.html': template.substitute(
            root='', page='blog.html', kind='website', title='Blog', description='Blog by Zongqi Wan.',
            language='en', header='          <h1>Blog</h1>', content=render_index(posts),
        ),
    }
    for post in posts:
        pages[OUTPUT / f'{post.slug}.html'] = render_post(post, template)

    # Validate the targets before replacing any previously generated pages.
    for path in pages:
        if path.exists() and GENERATED not in path.read_text(encoding='utf-8')[:160]:
            raise SystemExit(f'{path.relative_to(ROOT)} exists and was not generated by this script.')
    for path, html in pages.items():
        path.parent.mkdir(exist_ok=True)
        path.write_text(html, encoding='utf-8')
    for path in OUTPUT.glob('*.html'):
        if path not in pages and GENERATED in path.read_text(encoding='utf-8')[:160]:
            path.unlink()
    print(f'Built Blog and {len(posts)} post(s).')


if __name__ == '__main__':
    main()
